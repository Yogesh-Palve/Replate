import express from "express";
import cors from "cors";
import auth from "./modules/auth.js";
import donations from "./modules/donations.js";
import requests from "./modules/requests.js";
import volunteer from "./modules/volunteer.js";
import admin from "./modules/admin.js";
import { errorHandler } from "./utils/errors.js";
export const app = express();
app.use(cors({ origin: process.env.CORS_ORIGIN === "*" ? true : (process.env.CORS_ORIGIN || "").split(",") }));
app.use(express.json({ limit: "1mb" }));
app.get("/health", (_req, res) => res.json({ status: "ok", service: "replate-api" }));
app.use("/api/v1/auth", auth);
app.use("/api/v1/donations", donations);
app.use("/api/v1", requests);
app.use("/api/v1/requests", requests);
app.use("/api/v1/volunteer", volunteer);
app.use("/api/v1", volunteer);
app.use("/api/v1/admin", admin);
app.use(errorHandler);
